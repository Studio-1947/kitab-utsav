/*
  Builds the festival photo gallery from the Instagram export in public/posts.

  - Reads public/posts/metadata.json
  - Keeps event photographs (skips posters, programme cards, book covers, clippings)
  - Converts each to WebP (max 1600px on the long edge) in public/gallery/
  - Writes src/data/gallery.ts with edition, caption, credit, size and a placeholder colour

  Run: node scripts/build-gallery.mjs
*/
import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const SRC = path.join(ROOT, "public/posts");
const OUT = path.join(ROOT, "public/gallery");
const DATA = path.join(ROOT, "src/data/gallery.ts");
const MAX_EDGE = 1600;
const QUALITY = 78;

/* Posts are newest first; each edition is one contiguous run of indexes. */
const RANGES = [
  { from: 1, to: 34, edition: "bareilly-2026" },
  { from: 35, to: 129, edition: "indore-2026" },
  { from: 130, to: 171, edition: "patna-2026" },
  { from: 172, to: 217, edition: "mumbai-2026" },
  { from: 218, to: 297, edition: "bareilly-2025" },
  { from: 298, to: 345, edition: "bhopal-2025" },
  { from: 346, to: 356, edition: "delhi-2025" },
];

/* Single-image posts that are photographs (the rest are posters). */
const PHOTO_POSTS = new Set([27, 77, 169, 241, 306, 336, 347, 348]);

/* Carousel covers that are graphics, book covers, clippings or off-topic. */
const SKIP = new Set([13, 34, 45, 81, 98, 99, 101, 129, 170, 215, 218, 284, 305, 325, 339, 342, 344]);

const editionOf = (index) => RANGES.find((r) => index >= r.from && index <= r.to)?.edition;

/* Session title from the caption: the text before the festival boilerplate. */
function captionTitle(caption, own) {
  if (!own) return "";
  let t = caption.split(/•/)[0];
  t = t.split(/किताब उत्सव\s*[—–-]|राजकमल किताब उत्सव|किताब उत्सव - राजकमल|\[Kitab|दिनांक\s*:|तारीख़\s*:/)[0];
  t = t
    .replace(/#\S+/g, "")
    .replace(/[\p{Extended_Pictographic}\u{FE0F}\u{200D}]/gu, "")
    .replace(/\s+/g, " ")
    .trim();
  if (t.length > 120) t = t.slice(0, 117).replace(/\s+\S*$/, "") + "…";
  return t;
}

const hex = (n) => n.toString(16).padStart(2, "0");

async function main() {
  const posts = JSON.parse(await fs.readFile(path.join(SRC, "metadata.json"), "utf8"));
  await fs.rm(OUT, { recursive: true, force: true });
  await fs.mkdir(OUT, { recursive: true });

  const seen = new Set();
  const photos = [];
  let bytes = 0;

  for (const p of posts) {
    const keep = p.type === "carousel" ? !SKIP.has(p.index) : PHOTO_POSTS.has(p.index);
    const edition = editionOf(p.index);
    if (!keep || !edition || seen.has(p.shortcode)) continue;
    seen.add(p.shortcode);

    const file = `${edition}-${String(p.index).padStart(3, "0")}.webp`;
    const img = sharp(path.join(SRC, p.image_file), { limitInputPixels: false }).rotate();
    const info = await img
      .resize(MAX_EDGE, MAX_EDGE, { fit: "inside", withoutEnlargement: true })
      .webp({ quality: QUALITY, effort: 5 })
      .toFile(path.join(OUT, file));
    bytes += info.size;

    const { dominant } = await sharp(path.join(OUT, file)).stats();
    const owner = p.post_url.split("/")[3];
    const own = owner === "kitab.utsav";

    photos.push({
      src: `/gallery/${file}`,
      w: info.width,
      h: info.height,
      edition,
      title: captionTitle(p.caption, own),
      credit: own ? "" : `@${owner}`,
      href: p.post_url,
      color: `#${hex(dominant.r)}${hex(dominant.g)}${hex(dominant.b)}`,
    });
  }

  const ts = `/* Generated by scripts/build-gallery.mjs. Do not edit by hand. */

export type GalleryPhoto = {
  src: string;
  w: number;
  h: number;
  /** Edition slug, e.g. "bareilly-2026" */
  edition: string;
  /** Session title in Hindi, from the Instagram caption (empty for visitor posts) */
  title: string;
  /** Instagram handle for photos reposted from visitors */
  credit: string;
  /** Original Instagram post */
  href: string;
  /** Dominant colour, shown while the photo loads */
  color: string;
};

export const GALLERY: GalleryPhoto[] = ${JSON.stringify(photos, null, 1)};
`;
  await fs.writeFile(DATA, ts);
  console.log(`${photos.length} photos, ${(bytes / 1048576).toFixed(1)} MB of WebP in public/gallery`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
